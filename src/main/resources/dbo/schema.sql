CREATE TABLE IF NOT EXISTS usuarios (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome_completo VARCHAR(255) NOT NULL,
    email VARCHAR(255) NOT NULL UNIQUE,
    identificador VARCHAR(14) NOT NULL UNIQUE,
    tipo_usuario VARCHAR(2) NOT NULL,
    senha VARCHAR(255) NOT NULL,
    data_criacao TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    data_exclusao TIMESTAMP NULL,
    CONSTRAINT ck_usuario_tipo
    CHECK (tipo_usuario IN ('PF', 'PJ')),
    CONSTRAINT ck_usuario_identificador
    CHECK (
    (tipo_usuario = 'PF' AND LENGTH(identificador) = 11)
    OR
    (tipo_usuario = 'PJ' AND LENGTH(identificador) = 14)
    )
    );

CREATE TABLE IF NOT EXISTS CARTEIRAS (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    usuario_id BIGINT NOT NULL UNIQUE,
    saldo_reais DECIMAL(19, 2) NOT NULL DEFAULT 0,
    saldo_dolares DECIMAL(19, 4) NOT NULL DEFAULT 0,
    CONSTRAINT FK_CARTEIRA_USUARIO
    FOREIGN KEY (usuario_id)
    REFERENCES USUARIOS (ID),
    CONSTRAINT CK_CARTEIRA_SALDO_REAL
    CHECK (saldo_reais >= 0),
    CONSTRAINT CK_CARTEIRA_SALDO_DOLAR
    CHECK (saldo_dolares >= 0)
    );

CREATE TABLE IF NOT EXISTS TRANSFERENCIAS (
    ID BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    USUARIO_ORIGEM_ID BIGINT NOT NULL,
    USUARIO_DESTINO_ID BIGINT NOT NULL,
    VALOR_REAL DECIMAL(19, 2) NOT NULL,
    VALOR_DOLAR DECIMAL(19, 2) NOT NULL,
    COTACAO_COMPRA DECIMAL(19, 2) NOT NULL,
    DATA_COTACAO DATE NOT NULL,
    DATA_TRANSFERENCIA TIMESTAMP NOT NULL,
    STATUS VARCHAR(20) NOT NULL,
    CONSTRAINT FK_TRANSFERENCIA_ORIGEM
    FOREIGN KEY (USUARIO_ORIGEM_ID)
    REFERENCES USUARIOS (ID),
    CONSTRAINT FK_TRANSFERENCIA_DESTINO
    FOREIGN KEY (USUARIO_DESTINO_ID)
    REFERENCES USUARIOS (ID),
    CONSTRAINT CK_TRANSFERENCIA_VALOR_REAL
    CHECK (VALOR_REAL > 0),
    CONSTRAINT CK_TRANSFERENCIA_VALOR_DOLAR
    CHECK (VALOR_DOLAR > 0),
    CONSTRAINT CK_TRANSFERENCIA_USUARIOS
    CHECK (USUARIO_ORIGEM_ID <> USUARIO_DESTINO_ID)
    );

CREATE INDEX IF NOT EXISTS IDX_TRANSFERENCIA_ORIGEM_DATA
    ON TRANSFERENCIAS (
    USUARIO_ORIGEM_ID,
    DATA_TRANSFERENCIA
    );

